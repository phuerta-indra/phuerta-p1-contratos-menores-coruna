CREATE OR REPLACE TABLE CONTRATOS_MENORES_DB.MODELING.DIM_DATES AS
SELECT DISTINCT
    TO_NUMBER(TO_CHAR(FECHA, 'YYYYMMDD')) AS PK_FECHA,
    FECHA,
    YEAR(FECHA) AS ANHO,
    QUARTER(FECHA) AS TRIMESTRE,
    MONTH(FECHA) AS MES
FROM CONTRATOS_MENORES_DB.STAGING.CONTRATOS_STAGING
WHERE FECHA IS NOT NULL;