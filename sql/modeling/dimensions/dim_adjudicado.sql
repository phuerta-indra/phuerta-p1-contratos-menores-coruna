CREATE OR REPLACE TABLE CONTRATOS_MENORES_DB.MODELING.DIM_ADJUDICATARIO AS
SELECT
    ROW_NUMBER() OVER (ORDER BY ADJUDICATARIO, NIF) AS PK_ADJUDICATARIO,
    ADJUDICATARIO,
    NIF,
    CASE
        WHEN NIF LIKE '%*%' THEN 'Persona Física'
        ELSE 'Empresa'
    END AS TIPO_ADJUDICATARIO
FROM (
    SELECT DISTINCT ADJUDICATARIO, NIF
    FROM CONTRATOS_MENORES_DB.STAGING.CONTRATOS_STAGING
    WHERE ADJUDICATARIO IS NOT NULL
      AND NIF IS NOT NULL
);
