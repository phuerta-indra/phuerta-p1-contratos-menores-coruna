CREATE OR REPLACE TABLE CONTRATOS_MENORES_DB.MODELING.DIM_ADJUDICATARIO AS
SELECT
    ROW_NUMBER() OVER (ORDER BY ADJUDICATARIO, NIF) AS PK_ADJUDICATARIO,
    ADJUDICATARIO,
    NIF
FROM (
    SELECT DISTINCT ADJUDICATARIO, NIF
    FROM CONTRATOS_MENORES_DB.STAGING.CONTRATOS_STAGING
    WHERE ADJUDICATARIO IS NOT NULL
      AND NIF IS NOT NULL
);



ALTER TABLE CONTRATOS_MENORES_DB.MODELING.DIM_ADJUDICATARIO
ADD COLUMN TIPO_ADJUDICATARIO VARCHAR;



UPDATE CONTRATOS_MENORES_DB.MODELING.DIM_ADJUDICATARIO
SET TIPO_ADJUDICATARIO = CASE
    WHEN NIF LIKE '%*%' THEN 'Persona Fisica'
    ELSE 'Empresa'
END;