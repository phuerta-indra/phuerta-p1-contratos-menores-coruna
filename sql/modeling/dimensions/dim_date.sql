CREATE OR REPLACE TABLE CONTRATOS_MENORES_DB.MODELING.DIM_FECHAS AS
SELECT DISTINCT
    TO_NUMBER(TO_CHAR(FECHA, 'YYYYMMDD')) AS PK_FECHA,
    FECHA,
    YEAR(FECHA) AS ANHO,
    QUARTER(FECHA) AS TRIMESTRE,
    MONTH(FECHA) AS MES,
    CASE MONTH(FECHA)
        WHEN 1 THEN 'Enero'
        WHEN 2 THEN 'Febrero'
        WHEN 3 THEN 'Marzo'
        WHEN 4 THEN 'Abril'
        WHEN 5 THEN 'Mayo'
        WHEN 6 THEN 'Junio'
        WHEN 7 THEN 'Julio'
        WHEN 8 THEN 'Agosto'
        WHEN 9 THEN 'Septiembre'
        WHEN 10 THEN 'Octubre'
        WHEN 11 THEN 'Noviembre'
        WHEN 12 THEN 'Diciembre'
    END AS NOMBRE_MES
FROM CONTRATOS_MENORES_DB.STAGING.CONTRATOS_STAGING
WHERE FECHA IS NOT NULL;