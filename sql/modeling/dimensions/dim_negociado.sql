CREATE OR REPLACE TABLE CONTRATOS_MENORES_DB.MODELING.DIM_NEGOCIADO AS
SELECT
    ROW_NUMBER() OVER (ORDER BY CLAVE_NEGOCIADO) AS PK_NEGOCIADO,
    CLAVE_NEGOCIADO,
    NEGOCIADO_COD,
    NEGOCIADO
FROM (
    SELECT DISTINCT
        CLAVE_NEGOCIADO,
        NEGOCIADO_COD,
        NEGOCIADO
    FROM CONTRATOS_MENORES_DB.STAGING.CONTRATOS_STAGING
    WHERE CLAVE_NEGOCIADO IS NOT NULL
);