CREATE OR REPLACE TABLE CONTRATOS_MENORES_DB.MODELING.DIM_TIPO_CONTRATO AS
SELECT
    ROW_NUMBER() OVER (ORDER BY TIPO_CONTRATO) AS PK_TIPO_CONTRATO,
    TIPO_CONTRATO,
    CASE TIPO_CONTRATO
        WHEN 'A' THEN 'Obras'
        WHEN 'C' THEN 'Servicios'
        WHEN 'E' THEN 'Suministros'
        WHEN 'Z' THEN 'Otros'
    END AS DESCRIPCION_TIPO_CONTRATO,
    CASE TIPO_CONTRATO
        WHEN 'A' THEN 40000
        WHEN 'C' THEN 15000
        WHEN 'E' THEN 15000
        WHEN 'Z' THEN 15000
    END AS UMBRAL
FROM (
    SELECT DISTINCT TIPO_CONTRATO
    FROM CONTRATOS_MENORES_DB.STAGING.CONTRATOS_STAGING
    WHERE TIPO_CONTRATO IS NOT NULL
);