CREATE OR REPLACE TABLE CONTRATOS_MENORES_DB.MODELING.DIM_TIPO_CONTRATO AS
SELECT
    ROW_NUMBER() OVER (ORDER BY TIPO_CONTRATO) AS PK_TIPO_CONTRATO,
    TIPO_CONTRATO
FROM (
    SELECT DISTINCT TIPO_CONTRATO
    FROM CONTRATOS_MENORES_DB.STAGING.CONTRATOS_STAGING
    WHERE TIPO_CONTRATO IS NOT NULL
);