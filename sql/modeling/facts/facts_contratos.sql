CREATE OR REPLACE TABLE CONTRATOS_MENORES_DB.MODELING.FACT_CONTRATOS AS
SELECT
    s.REFERENCIA,
    d_f.PK_FECHA AS FK_FECHA, 
    d_tc.PK_TIPO_CONTRATO AS FK_TIPO_CONTRATO,
    d_a.PK_ADJUDICATARIO AS FK_ADJUDICATARIO,
    d_n.PK_NEGOCIADO AS FK_NEGOCIADO,
    s.PRECIO
FROM CONTRATOS_MENORES_DB.STAGING.CONTRATOS_STAGING AS s
LEFT JOIN CONTRATOS_MENORES_DB.MODELING.DIM_FECHAS AS d_f
    ON s.FECHA = d_f.FECHA
LEFT JOIN CONTRATOS_MENORES_DB.MODELING.DIM_TIPO_CONTRATO AS d_tc
    ON s.TIPO_CONTRATO = d_tc.TIPO_CONTRATO
LEFT JOIN CONTRATOS_MENORES_DB.MODELING.DIM_ADJUDICATARIO AS d_a
    ON s.ADJUDICATARIO = d_a.ADJUDICATARIO
   AND s.NIF = d_a.NIF
LEFT JOIN CONTRATOS_MENORES_DB.MODELING.DIM_NEGOCIADO AS d_n
    ON s.CLAVE_NEGOCIADO = d_n.CLAVE_NEGOCIADO;